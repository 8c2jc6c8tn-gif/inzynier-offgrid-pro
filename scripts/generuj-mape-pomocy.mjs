#!/usr/bin/env node
/**
 * Generator of the lazy help-loading map (`lib/i18n/pomoc/ladowanie.ts`).
 *
 * The help content („?” per field, „i” per screen) is large (all screens, three languages) and used to ship in the
 * common bundle of every page. Each module file in `lib/i18n/pomoc/` is now loaded on demand, by the screen id the
 * component asks for: this file maps every screen/group id to the module file that defines it.
 *
 * Source of truth: the `import * as <key> from "./<file>"` lines of `lib/i18n/pomoc/index.ts` (which modules exist)
 * and the top-level keys of `export const pl = { ... }` in each of those files (which screens they define), read with
 * the TypeScript AST. Nothing is written by hand.
 *
 *   node scripts/generuj-mape-pomocy.mjs           check only, exit 1 when `ladowanie.ts` is stale
 *   node scripts/generuj-mape-pomocy.mjs --write   regenerate `ladowanie.ts`
 */
import { createRequire } from "node:module"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const require = createRequire(import.meta.url)
const ts = require("typescript")

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const KATALOG = path.join(ROOT, "lib/i18n/pomoc")
const INDEKS = path.join(KATALOG, "index.ts")
const WYNIK = path.join(KATALOG, "ladowanie.ts")

function modulyZIndeksu() {
  const tekst = readFileSync(INDEKS, "utf8")
  return [...tekst.matchAll(/^import \* as (\w+) from "\.\/([\w-]+)"$/gm)].map((m) => ({ klucz: m[1], plik: m[2] }))
}

function klucze(plik) {
  const sciezka = path.join(KATALOG, `${plik}.ts`)
  const sf = ts.createSourceFile(sciezka, readFileSync(sciezka, "utf8"), ts.ScriptTarget.Latest, true)
  for (const st of sf.statements) {
    if (!ts.isVariableStatement(st)) continue
    for (const d of st.declarationList.declarations) {
      if (d.name.getText() !== "pl" || !d.initializer) continue
      let init = d.initializer
      while (ts.isAsExpression(init) || ts.isSatisfiesExpression(init) || ts.isParenthesizedExpression(init)) init = init.expression
      if (!ts.isObjectLiteralExpression(init)) throw new Error(`${plik}: \`pl\` nie jest literałem obiektu`)
      return init.properties.map((p) => {
        if (!ts.isPropertyAssignment(p) || !(ts.isStringLiteral(p.name) || ts.isIdentifier(p.name))) {
          throw new Error(`${plik}: nieobsługiwany element \`pl\` (${p.getText().slice(0, 40)})`)
        }
        return ts.isStringLiteral(p.name) ? p.name.text : p.name.getText()
      })
    }
  }
  throw new Error(`${plik}: brak \`export const pl\``)
}

export function zbuduj() {
  const moduly = modulyZIndeksu()
  if (moduly.length === 0) throw new Error("index.ts: nie znaleziono importów modułów pomocy")
  const poEkranie = new Map()
  for (const { klucz: k, plik } of moduly) {
    for (const id of klucze(plik)) {
      if (poEkranie.has(id)) throw new Error(`id "${id}" jest w dwóch plikach pomocy: ${poEkranie.get(id)} i ${k}`)
      poEkranie.set(id, k)
    }
  }
  const linie = [
    "// GENERATED by scripts/generuj-mape-pomocy.mjs — do not edit by hand (`pnpm pomoc:napraw` regenerates it).",
    "// Which help module file defines which screen/group id, and how to load that file on demand.",
    "",
    "export type ModulPomocy =",
    ...moduly.map((m) => `  | "${m.klucz}"`),
    "",
    "export type TresciModulu = { pl: object; en: object; ru: object }",
    "",
    "export const LADUJ_MODUL_POMOCY: Record<ModulPomocy, () => Promise<TresciModulu>> = {",
    ...moduly.map((m) => `  ${m.klucz}: () => import("./${m.plik}"),`),
    "}",
    "",
    "export const MODUL_POMOCY_PO_EKRANIE: Record<string, ModulPomocy> = {",
    ...[...poEkranie].map(([id, k]) => `  ${JSON.stringify(id)}: "${k}",`),
    "}",
    "",
  ]
  return linie.join("\n")
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const oczekiwane = zbuduj()
  if (process.argv.includes("--write")) {
    writeFileSync(WYNIK, oczekiwane)
    console.log(`generuj-mape-pomocy: zapisano ${path.relative(ROOT, WYNIK)}.`)
  } else {
    let biezace = ""
    try {
      biezace = readFileSync(WYNIK, "utf8")
    } catch {}
    if (biezace !== oczekiwane) {
      console.error("generuj-mape-pomocy: ladowanie.ts nieaktualne (napraw: pnpm pomoc:napraw).")
      process.exit(1)
    }
    console.log(`generuj-mape-pomocy OK — mapa ekranów pomocy zgodna z plikami modułów.`)
  }
}
