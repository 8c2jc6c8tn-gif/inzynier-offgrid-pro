#!/usr/bin/env node
/**
 * Generator of the UI-text aggregators (screen texts: `lib/i18n/ui/<grupa>.ts` = Polish, `<grupa>.en.ts`, `<grupa>.ru.ts`).
 *
 * One language per file lets a bundler ship Polish in the common bundle and English/Russian as lazy chunks
 * (`lib/i18n/rejestr-slownikow.ts`). Two kinds of aggregator are built from the files present in `lib/i18n/ui/`:
 *
 *   lib/i18n/ui-pl.ts, ui-en.ts, ui-ru.ts   one language each, named imports — what the app loads
 *   lib/i18n/ui/index.ts                    all three languages per group (`czesciUi`) + merged `uiPl/uiEn/uiRu` —
 *                                           for tests and scripts only; app code must not import it
 *
 * Source of truth: the group files themselves (every `<grupa>.ts` of the directory except `index.ts`; its `.en.ts` and
 * `.ru.ts` must exist). Groups are listed alphabetically; a key may live in one group only (a test checks it).
 * Nothing is written by hand: a new group = three files + `pnpm slowniki:napraw`.
 *
 *   node scripts/generuj-slowniki-ui.mjs           check only, exit 1 when stale or when a translation file is missing
 *   node scripts/generuj-slowniki-ui.mjs --write   regenerate the four files
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const KATALOG = path.join(ROOT, "lib/i18n")
const UI = path.join(KATALOG, "ui")
const JEZYKI = ["pl", "en", "ru"]
const NAGLOWEK = "// GENERATED by scripts/generuj-slowniki-ui.mjs — do not edit by hand (`pnpm slowniki:napraw` regenerates it)."

export function grupy() {
  const nazwy = readdirSync(UI)
  const wynik = nazwy.filter((n) => /^[\w-]+\.ts$/.test(n) && n !== "index.ts").map((n) => n.slice(0, -3)).sort()
  const braki = wynik.flatMap((g) => ["en", "ru"].filter((j) => !nazwy.includes(`${g}.${j}.ts`)).map((j) => `${g}.${j}.ts`))
  if (braki.length > 0) throw new Error(`brak plików tłumaczeń: ${braki.join(", ")} (każda grupa ma <grupa>.ts, <grupa>.en.ts i <grupa>.ru.ts)`)
  const sieroty = nazwy.filter((n) => /^[\w-]+\.(en|ru)\.ts$/.test(n) && !wynik.includes(n.replace(/\.(en|ru)\.ts$/, "")))
  if (sieroty.length > 0) throw new Error(`tłumaczenie bez pliku polskiego: ${sieroty.join(", ")}`)
  return wynik
}

const plik = (grupa, jezyk) => (jezyk === "pl" ? grupa : `${grupa}.${jezyk}`)
const nazwaZbioru = (j) => `ui${j[0].toUpperCase()}${j[1]}`

export function zbuduj() {
  const g = grupy()
  const wyniki = {}
  for (const j of JEZYKI) {
    wyniki[path.join(KATALOG, `ui-${j}.ts`)] = [
      NAGLOWEK,
      `// Screen texts in one language only (named imports, so the language can be a lazy chunk — lib/i18n/rejestr-slownikow.ts).`,
      "",
      ...g.map((x, i) => `import { ${j} as c${i} } from "./ui/${plik(x, j)}"`),
      "",
      `export const ${nazwaZbioru(j)}: Record<string, string> = Object.assign({}, ${g.map((_, i) => `c${i}`).join(", ")})`,
      "",
    ].join("\n")
  }
  wyniki[path.join(UI, "index.ts")] = [
    NAGLOWEK,
    "/**",
    " * Screen text — labels, headings and messages written by the UI itself (standard 17.1a), all three languages per group.",
    " * For tests and scripts only: the app loads one language at a time through `../ui-pl|en|ru.ts` and the lazy registry",
    " * (`../rejestr-slownikow.ts`); importing this file from app code would put every language in the common bundle.",
    " * Engine messages stay in `dictionary-*.ts`; the „?”/„i” help lives in `../pomoc`. A group = `<grupa>.ts` (Polish, the",
    " * source), `<grupa>.en.ts`, `<grupa>.ru.ts` (typed with the keys of `pl`, so a missing translation is a compile error, 17.1).",
    " * Keys start with `UI-` and are merged into the dictionaries, so screens use the same `t()` as everything else.",
    " * `pnpm check:i18n-guard` blocks new text written straight into JSX.",
    " */",
    ...g.flatMap((x, i) => JEZYKI.map((j) => `import { ${j} as ${j}${i} } from "./${plik(x, j)}"`)),
    "",
    `export const czesciUi = [${g.map((_, i) => `{ pl: pl${i}, en: en${i}, ru: ru${i} }`).join(", ")}] as const`,
    "",
    ...JEZYKI.map((j) => `export const ${nazwaZbioru(j)} = Object.assign({}, ...czesciUi.map((c) => c.${j})) as Record<string, string>`),
    "",
  ].join("\n")
  return wyniki
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let oczekiwane
  try {
    oczekiwane = zbuduj()
  } catch (e) {
    console.error(`generuj-slowniki-ui: ${e.message}`)
    process.exit(1)
  }
  if (process.argv.includes("--write")) {
    for (const [sciezka, tresc] of Object.entries(oczekiwane)) writeFileSync(sciezka, tresc)
    console.log("generuj-slowniki-ui: zapisano lib/i18n/ui-{pl,en,ru}.ts i lib/i18n/ui/index.ts.")
  } else {
    const nieaktualne = Object.entries(oczekiwane)
      .filter(([sciezka, tresc]) => {
        try {
          return readFileSync(sciezka, "utf8") !== tresc
        } catch {
          return true
        }
      })
      .map(([sciezka]) => path.relative(ROOT, sciezka))
    if (nieaktualne.length > 0) {
      console.error(`generuj-slowniki-ui: nieaktualne: ${nieaktualne.join(", ")} (napraw: pnpm slowniki:napraw).`)
      process.exit(1)
    }
    console.log("generuj-slowniki-ui OK — agregaty tekstów ekranów zgodne z plikami grup.")
  }
}
